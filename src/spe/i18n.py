"""UI language: English (the strings in the code) or Italian, from the user's Sure locale.

Strings are written in English where they are used, wrapped in _("…") (templates) or tr("…") (Python), with
%(name)s placeholders; IT maps each to Italian. tests/test_i18n.py fails when a wrapped string has no Italian.
"""

from typing import Any


def language(locale: str | None) -> str:
    return "it" if (locale or "it").lower().startswith("it") else "en"


class Tr:
    def __init__(self, lang: str):
        self.lang = lang

    def __call__(self, text: str, **values: Any) -> str:
        out = IT.get(text, text) if self.lang == "it" else text
        return out % values if values else out

    def n(self, one: str, many: str, count: int, **values: Any) -> str:
        return self(one if count == 1 else many, n=count, **values)


